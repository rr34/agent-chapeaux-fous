test("owning tool contracts explain inputs and results without a database or schema catalog", () => {
  const registry = registerNativeCapabilities(new ToolRegistry());
  registerCalendarTools(registry, {}, {}, {});
  registerContactTools(registry, {}, {}, {});
  registerJournalTools(registry, {}, {});
  registerTodoTools(registry, {}, {});
  const definitions = Object.fromEntries(registry.toolDefinitions().map(tool => [tool.name, tool]));
  assert.match(definitions.journal_add.inputSchema.properties.number_value.description, /parent tracker's canonical unit/);
  assert.match(definitions.tracker_create.description, /without creating journal entries/);
  assert.equal(Object.hasOwn(
    definitions.tracker_create.inputSchema.properties.trackers.items.properties,
    "content_text",
  ), false);
  assert.deepEqual(
    definitions.tracker_list.inputSchema.properties.result_filter.properties.collection_path.enum,
    ["/trackers", "/groups"],
  );
  assert.match(definitions.journal_list.outputSchema.properties.entries.items.properties.external_id.description, /idempotent/);
  assert.match(definitions.calendar_event_update.description, /concrete event generated by a calendar routine/);
  assert.match(definitions.calendar_event_update.description, /does not rewrite its routine or sibling events/);
  assert.match(definitions.calendar_event_update.inputSchema.properties.ends_at_utc.description, /empty string clears it.*start-only point/);
  assert.match(definitions.calendar_event_occurrence_update.description, /computed occurrence.*RRULE/);
  assert.match(definitions.calendar_event_occurrence_update.description, /not an RRULE occurrence/);
  assert.match(definitions.calendar_event_add.inputSchema.properties.is_all_day.description, /^True when/);
  assert.match(definitions.calendar_event_add.description, /start time without an end or duration.*point event.*ends_at_utc=null/);
  assert.match(definitions.calendar_event_add.inputSchema.properties.ends_at_utc.description, /start-only point event/);
  assert.equal(Object.hasOwn(definitions.todo_update.inputSchema.properties.updates.items.properties, "duration_minutes"), false);
  assert.equal(Object.hasOwn(definitions.todo_add.inputSchema.properties, "scheduled_at_utc"), false);
  assert.equal(definitions.todo_add.inputSchema.properties.status.enum.includes("unplanned"), false);
  assert.match(definitions.calendar_routine_add.description, /generates concrete calendar events only/);
  assert.equal(definitions.calendar_routine_list.annotations.readOnlyHint, true);
  assert.match(definitions.calendar_routine_update.description, /reversible delete lifecycle/);
  assert.match(definitions.calendar_routine_update.description, /rather than claiming permanent erasure/);
  assert.equal(
    definitions.calendar_routine_update.metadata["agent-slayer/selection"].actionClasses.includes("DELETE"),
    true,
  );
  assert.match(definitions.calendar_event_todo_link_set.description, /linked=false removes it/);
  assert.equal(definitions.calendar_event_todo_link_set.annotations.idempotentHint, true);
  assert.match(definitions.calendar_routine_generate.description, /earliest current or upcoming event/);
  assert.ok(definitions.contact_search.outputSchema.properties.matches.items.properties.display_name.description);
  assert.match(
    definitions.contact_search.outputSchema.properties.matches.items.properties
      .methods.items.properties.id.description,
    /address_method_id/,
  );
  assert.deepEqual(
    definitions.contact_address_update.inputSchema.properties.updates.items.properties.action.enum,
    ["add", "replace"],
  );
  assert.deepEqual(
    definitions.contact_address_update.metadata["agent-slayer/selection"].actionClasses,
    ["CREATE", "UPDATE"],
  );
  assert.match(definitions.contact_address_update.description, /additional address/);
  assert.equal(schemaProblem({ updated_count: 1, items: [{ task: { text: "Updated task" } }] }, definitions.todo_update.outputSchema), null);
});

test("profile tool returns its owning function's result without schema metadata or an extra trace", async () => {
  const registry = new ToolRegistry();
  let calls = 0;
  registerProfileFactTools(registry, {
    list({ status, factTypes }) {
      calls++;
      assert.equal(status, "active");
      assert.deepEqual(factTypes, ["vehicle"]);
      return { status, count: 1, facts: [{ id: 42, factType: "vehicle", text: "My car is blue.", status: "active" }] };
    },
  });
  const result = await registry.execute("profile_fact_list", { status: "active", fact_types: ["vehicle"] });
  assert.equal(calls, 1);
  assert.equal(result.facts[0].fact_text, "My car is blue.");
  assert.equal(Object.hasOwn(result, "schemaProjection"), false);
  const schema = registry.toolDefinitions()[0].outputSchema;
  assert.match(schema.properties.facts.items.properties.fact_text.description, /Self-contained/);
  assert.equal(schemaProblem(result, schema), null);
});

test("contact tag relationship mutations return literal per-contact evidence", async () => {
  const registry = registerNativeCapabilities(new ToolRegistry());
  const contact = {
    contact_id: 399,
    display_name: "Emily Wu",
    status: "active",
    updated_at_utc: "2026-11-01T23:07:05.051Z",
  };
  registerContactTools(registry, {}, {
    addTagToContacts() {
      return {
        tag: "St. Mary School",
        selectedContactCount: 1,
        taggedContactCount: 1,
        alreadyTaggedContactCount: 0,
        results: [{ status: "tagged", contact }],
      };
    },
    removeTagFromContacts() {
      return {
        tag: "St. Mary School",
        selectedContactCount: 1,
        unlinkedContactCount: 0,
        alreadyUnlinkedContactCount: 1,
        results: [{ status: "already_unlinked", contact }],
      };
    },
  }, {});
  const definitions = new Map(registry.toolDefinitions().map((definition) => [
    definition.name, definition,
  ]));
  const added = await registry.execute("contact_tag_add_batch", {
    tag: "St. Mary School", contact_ids: [399],
  });
  assert.equal(schemaProblem(added, definitions.get("contact_tag_add_batch").outputSchema), null);
  assert.deepEqual(added.results, [{
    status: "tagged",
    contact: { ...contact, ref: "agent-slayer://contacts/399" },
  }]);
  const groups = objectReferenceGroupsFromToolResult({
    toolDefinition: definitions.get("contact_tag_add_batch"),
    toolDefinitions: [...definitions.values()],
    result: added,
    sourceEventSeq: 42,
  });
  assert.deepEqual(groups, [{
    mention: "Contact returned by contact_tag_add_batch",
    role: "subject",
    type: "contacts.contact",
    source: "native:contacts",
    objects: [{ id: 399, ref: "agent-slayer://contacts/399", display: "Emily Wu" }],
    sourceEventSeqs: [42],
  }]);

  const unlinked = await registry.execute("contact_tag_unlink_batch", {
    tag: "St. Mary School", contact_ids: [399],
  });
  assert.equal(
    schemaProblem(unlinked, definitions.get("contact_tag_unlink_batch").outputSchema),
    null,
  );
  assert.equal(unlinked.results[0].status, "already_unlinked");
});
